const UNKNOWN = '##### #...# #...# #...# #...# #...# #####';

const TABLE = new Map();
function parse(s) { return s.split(' ').map(r => [...r].reduce((m, c) => (m << 1) | (c === '#' ? 1 : 0), 0)); }
for (const k in RAW) TABLE.set(k.charCodeAt(0), parse(RAW[k]));
TABLE.set(0xb0, TABLE.get(0xdf));                 // '°' typed by a user
const BOX = parse(UNKNOWN);

export const GLYPH_W = 5, GLYPH_H = 7;
// 7 numbers, bit 4 = the left dot
export function glyphRows(code) {
  return TABLE.get(code) || BOX;
}
export const glyphCodes = () => [...TABLE.keys()];

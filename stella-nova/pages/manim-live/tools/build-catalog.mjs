#!/usr/bin/env node
// ============================================================================
//  MANIM LIVE  ·  tools/build-catalog.mjs  (examples/*.py -> examples/catalog.js)
// ----------------------------------------------------------------------------
//  Reads the header of each examples/<domain>-<slug>.py file:
//    # title: Riemann sums
//    # topic: Calculus             (one of examples/TOPICS.md, exact)
//    # level: 1|2|3
//    # scene: RiemannSums          (a class defined in the file)
//    # summary: one plain sentence
//    # concepts: Axes, get_riemann_rectangles, ValueTracker
//  and writes examples/catalog.js:
//    export const TOPICS = [...];   export const CATALOG = [{id, file, title,
//    topic, level, scene, summary, concepts}, ...]
//  sorted by topic order, then level, then title.
//
//  Usage:  node tools/build-catalog.mjs [--check]
//    --check  validate only; exit 1 on any error, write nothing
// ============================================================================

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const PAGE = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const EX = path.join(PAGE, 'examples');
const REQUIRED = ['title', 'topic', 'level', 'scene', 'summary', 'concepts'];

export function readTopics() {
  const md = fs.readFileSync(path.join(EX, 'TOPICS.md'), 'utf8');
  return md.split('\n').filter((l) => l.startsWith('- ')).map((l) => l.slice(2).trim());
}

export function parseHeader(src) {
  const out = {};
  for (const line of src.split('\n')) {
    const m = /^#\s*([a-z]+)\s*:\s*(.*)$/.exec(line);
    if (!m) {
      if (line.trim() === '' || line.startsWith('#')) continue;
      break;
    }
    out[m[1]] = m[2].trim();
  }
  return out;
}

export function buildCatalog() {
  const topics = readTopics();
  const errors = [];
  const entries = [];
  const files = fs.readdirSync(EX).filter((f) => f.endsWith('.py')).sort();
  for (const file of files) {
    const src = fs.readFileSync(path.join(EX, file), 'utf8');
    const h = parseHeader(src);
    const where = `examples/${file}`;
    for (const k of REQUIRED) if (!h[k]) errors.push(`${where}: missing "# ${k}:"`);
    if (!/^[a-z0-9]+(-[a-z0-9]+)+\.py$/.test(file)) errors.push(`${where}: name must be <domain>-<slug>.py in lower case`);
    if (h.topic && !topics.includes(h.topic)) errors.push(`${where}: topic "${h.topic}" is not in examples/TOPICS.md`);
    const level = Number(h.level);
    if (h.level && ![1, 2, 3].includes(level)) errors.push(`${where}: level must be 1, 2 or 3`);
    if (h.scene && !new RegExp(`^class\\s+${h.scene}\\s*\\(`, 'm').test(src)) errors.push(`${where}: scene class ${h.scene} is not defined`);
    if (!/^from manim import \*/m.test(src)) errors.push(`${where}: needs "from manim import *"`);
    entries.push({
      id: file.replace(/\.py$/, ''),
      file,
      title: h.title || '',
      topic: h.topic || '',
      level: level || 1,
      scene: h.scene || '',
      summary: h.summary || '',
      concepts: (h.concepts || '').split(',').map((s) => s.trim()).filter(Boolean),
    });
  }
  const ids = new Set();
  for (const e of entries) {
    if (ids.has(e.id)) errors.push(`duplicate id ${e.id}`);
    ids.add(e.id);
  }
  entries.sort((a, b) => topics.indexOf(a.topic) - topics.indexOf(b.topic) || a.level - b.level || a.title.localeCompare(b.title));
  return { topics, entries, errors };
}

export function catalogSource({ topics, entries }) {
  return '// Generated by tools/build-catalog.mjs from the headers of examples/*.py.\n'
    + '// Do not edit by hand: change the example file and run the tool.\n'
    + `export const TOPICS = ${JSON.stringify(topics, null, 1)};\n`
    + `export const CATALOG = ${JSON.stringify(entries, null, 1)};\n`
    + 'export default CATALOG;\n';
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const check = process.argv.includes('--check');
  const cat = buildCatalog();
  if (cat.errors.length) {
    for (const e of cat.errors) console.error('error: ' + e);
    process.exit(1);
  }
  if (!check) fs.writeFileSync(path.join(EX, 'catalog.js'), catalogSource(cat));
  const byTopic = {};
  for (const e of cat.entries) byTopic[e.topic] = (byTopic[e.topic] || 0) + 1;
  console.log(`${check ? 'checked' : 'wrote examples/catalog.js:'} ${cat.entries.length} examples, ${Object.keys(byTopic).length} topics`);
}
